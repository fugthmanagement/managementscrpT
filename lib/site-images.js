// Electricians and plumbers share the properly licensed trade portfolio until
// their own approved original photos are uploaded. Never fall back to office stock.
const photoIndustry=industry=>({electrician:"contractor",plumber:"contractor"})[industry]||industry;
export function getSiteImage(id,industry="general") {
 const actual=photoIndustry(industry);
 const matching=SITE_IMAGES.find(x=>x.id===id&&x.industry===actual);
 return matching||SITE_IMAGES.find(x=>x.industry===actual)||SITE_IMAGES[0];
}
export function getIndustryPhotos(industry="general") {return SITE_IMAGES.filter(x=>x.industry===photoIndustry(industry));}
export function imageBelongsToIndustry(imageId,industry) {return SITE_IMAGES.some(x=>x.id===imageId&&x.industry===photoIndustry(industry));}
